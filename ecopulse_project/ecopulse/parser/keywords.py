# Категории для определения типа инцидента
INCIDENT_CATEGORIES = {
    "экологический":  ECOLOGY_WORDS,
    "промышленный":   INDUSTRIAL_WORDS,
    "жалоба":         COMPLAINT_WORDS,
    "регуляторный":   REGULATORY_WORDS,
    "здоровье":       HEALTH_WORDS,
    "трудовой":       LABOR_WORDS,
}


def get_incident_category(text: str) -> str:
    text_lower = text.lower()
    scores = {}
    for category, words in INCIDENT_CATEGORIES.items():
        score = sum(1 for w in words if w in text_lower)
        if score > 0:
            scores[category] = score
    if not scores:
        return "не определён"
    return max(scores, key=scores.get)


def is_spam(text: str, threshold: int = 2) -> bool:
    text_lower = text.lower()
    matches = sum(1 for w in STOP_WORDS if w in text_lower)
    return matches >= threshold


def is_priority(text: str) -> bool:
    text_lower = text.lower()
    return any(w in text_lower for w in PRIORITY_WORDS)
